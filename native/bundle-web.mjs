import { readFile, readdir, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const wasmPath = process.argv[2];
if (!wasmPath) {
  console.error("Usage: node native/bundle-web.mjs <path-to-code_lang.wasm>");
  process.exit(2);
}

const project = fileURLToPath(new URL("../", import.meta.url));
const examplesDirectory = join(project, "examples");
const names = (await readdir(examplesDirectory))
  .filter((name) => name.endsWith(".code"))
  .sort();
const examples = Object.fromEntries(await Promise.all(
  names.map(async (name) => [name, await readFile(join(examplesDirectory, name), "utf8")]),
));
const wasm = await readFile(wasmPath);
if (!WebAssembly.validate(wasm)) {
  throw new Error("The supplied file is not a valid WebAssembly module");
}

const payload = { wasm: wasm.toString("base64"), examples };
await writeFile(
  join(project, "docs", "code-web-data.js"),
  "// Generated by native/bundle-web.mjs.\n" +
  "globalThis.CodePlaygroundBundle = " + JSON.stringify(payload) + ";\n",
);
console.log(`Bundled ${wasm.length.toLocaleString()} WebAssembly bytes and ${names.length} examples.`);
